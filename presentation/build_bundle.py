"""Bundle the tracker source into presentation/bundle.js and record outputs.

    python presentation/build_bundle.py

Run it from anywhere after changing service_tracker/, the generator, data/,
deck.py, or a snippet in index.html. It does three things:

1. Copies the package, the generator, data/ and deck.py into bundle.js, so
   the page can run the real code in the browser without a web server.
2. Runs every snippet in index.html once with this Python, in page order.
3. Stores each snippet's output in bundle.js. The page shows that recorded
   output if the browser cannot load Python (no internet, blocked CDN).

Uses only the standard library.
"""

import json
import re
import shutil
import sys
import tempfile
import textwrap
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

SNIPPET = re.compile(
    r'<script type="text/x-python" id="([^"]+)">(.*?)</script>', re.DOTALL
)


def clean(code):
    """Same normalisation as the page: dedent and trim blank edge lines."""
    return textwrap.dedent(code).strip("\n") + "\n"


def collect_files():
    """Map workspace path to text for everything the snippets can import."""
    files = {}
    for path in sorted((ROOT / "service_tracker").rglob("*.py")):
        files[path.relative_to(ROOT).as_posix()] = path.read_text(encoding="utf-8")
    generator = ROOT / "scripts" / "generate_data.py"
    files["scripts/generate_data.py"] = generator.read_text(encoding="utf-8")
    for path in sorted((ROOT / "data").iterdir()):
        if path.is_file() and path.suffix in {".csv", ".json"}:
            files[f"data/{path.name}"] = path.read_text(encoding="utf-8")
    files["deck.py"] = (HERE / "deck.py").read_text(encoding="utf-8")
    return files


def snippets():
    html = (HERE / "index.html").read_text(encoding="utf-8")
    found = [(sid, clean(code)) for sid, code in SNIPPET.findall(html)]
    ids = [sid for sid, _ in found]
    duplicates = {sid for sid in ids if ids.count(sid) > 1}
    if duplicates:
        sys.exit(f"duplicate snippet ids in index.html: {sorted(duplicates)}")
    return found


def record(files, found):
    """Run each snippet in a throwaway copy of the workspace."""
    workdir = Path(tempfile.mkdtemp(prefix="tracker-deck-"))
    try:
        for name, text in files.items():
            target = workdir / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        sys.path[:0] = [str(workdir), str(workdir / "scripts")]
        import deck  # the copy in workdir

        recorded = {}
        for sid, code in found:
            result = json.loads(deck.run_snippet(code, str(workdir)))
            status = "ok" if result["ok"] else "ERROR"
            print(f"  {sid:<16} {status}  {len(result['visuals'])} visuals")
            recorded[sid] = {"code": code, "result": result}
        return recorded
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


def main():
    files = collect_files()
    found = snippets()
    print(f"Recording {len(found)} snippets with Python {sys.version.split()[0]}")
    recorded = record(files, found)
    bundle = {
        "built": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "python": sys.version.split()[0],
        "files": files,
        "recorded": recorded,
    }
    out = HERE / "bundle.js"
    out.write_text(
        "// Generated by presentation/build_bundle.py. Do not edit by hand.\n"
        "window.TRACKER_BUNDLE = " + json.dumps(bundle, indent=1) + ";\n",
        encoding="utf-8",
    )
    failed = [sid for sid, r in recorded.items() if not r["result"]["ok"]]
    print(f"Wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
    if failed:
        sys.exit(f"snippets with errors: {', '.join(failed)}")


if __name__ == "__main__":
    main()
